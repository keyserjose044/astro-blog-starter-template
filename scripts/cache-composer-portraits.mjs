import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUTPUT_DIR = path.join(ROOT, 'public', 'images_webp', 'composers');
const GENERATED_DIR = path.join(ROOT, 'src', 'generated');
const MANIFEST_PATH = path.join(GENERATED_DIR, 'composerPortraits.ts');

const TOKEN = process.env.RAINDROP_TOKEN || '';
const COLLECTION_ID = process.env.RAINDROP_COLLECTION_COMPOSERS_ID || '58399760';
const PER_PAGE = 50;
const CONCURRENCY = 6;

const CONTENT_TYPE_EXTENSIONS = new Map([
  ['image/jpeg', 'jpg'],
  ['image/jpg', 'jpg'],
  ['image/png', 'png'],
  ['image/webp', 'webp'],
  ['image/gif', 'gif'],
  ['image/svg+xml', 'svg'],
]);

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function unique(values) {
  return [...new Set(values.map((value) => String(value || '').trim()).filter(Boolean))];
}

function mediaLinks(item) {
  return Array.isArray(item?.media)
    ? item.media.map((entry) => entry?.link).filter((value) => typeof value === 'string')
    : [];
}

function extensionFromResponse(response, url) {
  const contentType = String(response.headers.get('content-type') || '')
    .split(';', 1)[0]
    .trim()
    .toLowerCase();
  const known = CONTENT_TYPE_EXTENSIONS.get(contentType);
  if (known) return known;

  try {
    const pathname = new URL(url).pathname;
    const ext = path.extname(pathname).replace('.', '').toLowerCase();
    if (['jpg', 'jpeg', 'png', 'webp', 'gif', 'svg'].includes(ext)) {
      return ext === 'jpeg' ? 'jpg' : ext;
    }
  } catch {
    // Ignore malformed cover URLs.
  }

  return '';
}

async function writeManifest(manifest) {
  await mkdir(GENERATED_DIR, { recursive: true });
  const ordered = Object.fromEntries(
    Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true })),
  );
  const source = `// Generated by scripts/cache-composer-portraits.mjs. Do not edit by hand.\nconst composerPortraits: Record<string, string> = ${JSON.stringify(ordered, null, 2)};\n\nexport default composerPortraits;\n`;
  await writeFile(MANIFEST_PATH, source, 'utf8');
}

async function fetchRaindrops() {
  const items = [];
  let page = 0;

  while (true) {
    const url = new URL(`https://api.raindrop.io/rest/v1/raindrops/${COLLECTION_ID}`);
    url.searchParams.set('perpage', String(PER_PAGE));
    url.searchParams.set('page', String(page));
    url.searchParams.set('sort', '-created');

    const response = await fetch(url, {
      headers: {
        Authorization: `Bearer ${TOKEN}`,
        Accept: 'application/json',
      },
    });

    if (!response.ok) {
      throw new Error(`Raindrop composer fetch failed with ${response.status}`);
    }

    const batch = (await response.json())?.items || [];
    if (!batch.length) break;
    items.push(...batch);
    if (batch.length < PER_PAGE) break;
    page += 1;
    await sleep(350);
  }

  return items;
}

async function cachePortrait(item) {
  const id = String(item?._id || '').trim();
  if (!id) return null;

  const candidates = unique([item?.cover, ...mediaLinks(item)]).filter((url) => /^https?:\/\//i.test(url));

  for (const url of candidates) {
    try {
      const response = await fetch(url, {
        redirect: 'follow',
        headers: {
          Accept: 'image/avif,image/webp,image/apng,image/svg+xml,image/*,*/*;q=0.8',
          'User-Agent': 'LifeLoggerz/1.0 (+https://lifeloggerz.com)',
        },
      });
      if (!response.ok) continue;

      const extension = extensionFromResponse(response, url);
      if (!extension) continue;

      const bytes = Buffer.from(await response.arrayBuffer());
      if (bytes.length < 256) continue;

      const filename = `${id}.${extension}`;
      await writeFile(path.join(OUTPUT_DIR, filename), bytes);
      return `/images_webp/composers/${filename}`;
    } catch (error) {
      console.warn(`[composer portraits] ${id}: ${url} failed`, error instanceof Error ? error.message : error);
    }
  }

  return null;
}

async function mapWithConcurrency(items, worker) {
  const results = new Array(items.length);
  let nextIndex = 0;

  async function runWorker() {
    while (true) {
      const index = nextIndex;
      nextIndex += 1;
      if (index >= items.length) return;
      results[index] = await worker(items[index]);
    }
  }

  await Promise.all(Array.from({ length: Math.min(CONCURRENCY, items.length || 1) }, runWorker));
  return results;
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });
  await mkdir(GENERATED_DIR, { recursive: true });

  // A build without the Raindrop secret should still compile cleanly (for example PR validation).
  if (!TOKEN) {
    await writeManifest({});
    console.warn('[composer portraits] RAINDROP_TOKEN missing; using remote portraits for this build.');
    return;
  }

  const items = await fetchRaindrops();

  // The directory is generated for each production build so deleted/replaced Raindrop profiles
  // do not leave stale public assets behind.
  for (const entry of await readdir(OUTPUT_DIR, { withFileTypes: true })) {
    if (entry.isFile()) await rm(path.join(OUTPUT_DIR, entry.name));
  }

  const localPaths = await mapWithConcurrency(items, cachePortrait);
  const manifest = {};
  localPaths.forEach((localPath, index) => {
    if (localPath) manifest[String(items[index]._id)] = localPath;
  });

  await writeManifest(manifest);
  console.log(`[composer portraits] cached ${Object.keys(manifest).length}/${items.length} profiled portraits locally.`);
}

main().catch(async (error) => {
  console.warn('[composer portraits] cache step failed; falling back to remote portrait URLs.', error);
  await writeManifest({});
  process.exitCode = 0;
});
